def get_twelve_spirit(heavenly_stem: str, earthly_branch: str) -> dict:
    """
    천간과 지지로 십이운성 조회

    Args:
        heavenly_stem: 천간 (갑, 을, 병...)
        earthly_branch: 지지 (자, 축, 인...)

    Returns:
        십이운성 정보 딕셔너리
    """
    spirit_name = TWELVE_SPIRITS.get((heavenly_stem, earthly_branch))

    if spirit_name:
        info = TWELVE_SPIRITS_DESC[spirit_name].copy()
        info["spirit"] = spirit_name
        return info

    return {
        "spirit": None,
        "name": "알 수 없음",
        "strength": 50,
        "description": "정보 없음"
    }
